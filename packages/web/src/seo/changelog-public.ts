/**
 * 公开更新记录页的**唯一内容源**（渠道台账 C8）。
 *
 * ★ 为什么是手写的一份而不是从内部 `CHANGELOG.md` 脱敏：
 *   内部那本 217 行，每行都是施工叙述——服务器路径、端口、systemd 单元名、内部挂账、
 *   未验账全在里面。拿正则去洗它，等于把红线的成败交给「我有没有漏一种写法」，
 *   而这一页正是全站唯一对外宣称事实的地方。手写一份新的，红线就变成结构性的：
 *   **没写进来的东西不可能漏出去**。
 * ★ 代价如实记在这里：发一版要记得回来加一条，忘了就是这页落后于线上。
 *   这条落后机器拦不住（只拦得住「凭空造一个版本号」那一头），所以同时登记了
 *   `docs/GROWTH-CHANNELS.md` 的已知代价与一条真人测试单。
 * ★ 三条与词条语料同族的口径（`docs/SEO-SPEC.md` §4）：不写使用量数字、
 *   不许诺效果、不引用真实用户。所以这里的条目只说「哪里变了、你点进去会看到什么」。
 */

export interface ReleaseNote {
  /** 版本号；与发版记录同名，纯 ASCII，同时决定页内锚点 */
  version: string;
  /** 线上生效日期（YYYY-MM-DD）*/
  date: string;
  /** 这一版对用户而言是哪一句话 */
  headline: string;
  /** 逐条变化：一条一件可验证的事，不写内部动因 */
  items: string[];
}

