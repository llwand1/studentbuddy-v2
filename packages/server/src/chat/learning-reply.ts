/** 普通对话的表达约束紧随本轮偏好，避免被长工具说明及旧风格句淹没。 */
import { buildAnswerStyleBlock, type AnswerStyle } from '@sb/shared';

export function buildChatStyleBlock(style: AnswerStyle, text = ''): string {
  const calculation = /(?:解(?:方程|不等式)|计算(?!机)|求(?:解|值|导|积分)|化简|证明|推导)/u.test(text)
    || /\d[^\n]{0,80}[=＝][^\n]{0,80}\d/u.test(text);
  const opening = style.tone === 'socratic'
    ? '本轮使用引导式口吻：先问一个关键问题，让学习者自己想一步；不抢先泄露答案，不强加结论和关键词模板，不仅因存在多种讲法就弹选择卡。'
    : calculation
      ? '本轮是求解、计算或推导：开篇只给求解路线（先做什么、再做什么），接一行「关键词：`方法一` · `方法二`」。不要写「核心结论」或提前报最终数值；按步骤推导，最终结果与代入验算放在一起，核对一致再交付。这条计算顺序优先于前面的开篇习惯；用户明确只要答案时先核对再给，不能把猜测当检查点。'
      : '解释概念、纠错时，先用一句话给核心结论，再用一行「关键词：`概念一` · `概念二`」列2–3个相关概念。遇到计算题开篇先给求解路线，不先报最终数值，推导后把结果与代入验算放在一起。';
  const depth = style.verbosity === 'brief'
    ? `本轮简短：${style.tone === 'socratic' ? '只问关键问题、给必要提示' : '保留核心判断或求解路线、关键词和最关键理由'}，两三句内，不强行分步或加入练习邀请。`
    : '分步讲解时，每步连起来说清「做了什么 → 为什么这样做 → 得到了什么、如何接下一步」，用短段或列点，不机械拆成三个小标题；图配在对应解释旁。详略、举例与排版遵从用户偏好和本轮明确请求。';
  return [buildAnswerStyleBlock(style), '【本轮学习回复】以下规则仅用于知识讲解；闲聊、操作回执和仅出题不用这个模板。', opening, depth,
    'GrillMe 按问答节奏先问关键问题，不抢先泄露练习答案。完整讲解后可以邀请用自己的话复述一个关键原因，或建议打开 GrillMe、选当前对话范围练一轮；只给一个自愿的下一步，不每轮邀请、不叠加对战邀约。正式出题仍用 generate_quiz，不推荐不存在的「深度理解模式」，不强制作答才能继续。',
  ].join('\n');
}
