/**
 * chat/date-context —— 让模型知道「今天是几月几号」的那一段（2026-09-17 新建）。
 *
 * 【存在理由：模型没有时钟，这是事实缺失，不是能力缺失】
 * 用户问「今天几号」「距离考试还有几天」时，模型手里没有任何日期信息，
 * 只能瞎猜一个日期，或者说「我的知识截止到……」。修法不是在提示词里教它算日期
 * （那是在错的层修：它连「今天」这个起点都没有），而是每轮把当天日期作为一段
 * system 喂进去——和我们把词条、资料、画像喂进去是同一个手法。
 *
 * 【三条刻意的设计】
 * ① **只到「日」，不含时分秒**：段内容必须**一天之内恒定**。本仓的 system 前缀是
 *    prompt 缓存（Anthropic / OpenAI 的 prefix cache）的匹配前缀，若每轮都带一个新
 *    时间戳，缓存**永远不会命中**，长对话的延迟与费用双双上升。代价是模型不知道
 *    「现在几点」——本需求（知道今天几月几号）用不到，真需要时再单独评估。
 * ② **本地时区，绝不用 `toISOString()`**：那个方法按 UTC 出日期，北京时间 08:00
 *    之前会算成**昨天**（UTC+8 的 09-17 00:30 == UTC 的 09-16 16:30）——用户一大早
 *    问「今天几号」正好拿到错答案，且错得不显眼。故一律走 `getFullYear` /
 *    `getMonth` / `getDate` 这套**本地**取值。单机应用（127.0.0.1 + 本地 SQLite）
 *    里服务端时区 === 用户时区，本地即正确。
 * ③ **时间可注入**（`now` 参数）：不注入就没法测边界（凌晨、跨月、跨年、闰日），
 *    而这类边界恰恰是日期代码唯一会错的地方。生产调用一律不传。
 *
 * ⚠️ 本段计入 `systemPromptTokens`（见 `context-segments.ts`）——它**恒非空、每轮都发**，
 *    所以措辞要短：每多 10 字就是每轮多 10 token，且等于少载一截历史。
 */
/** `Date.getDay()` 是 0=周日，故下表按周日打头。 */
const WEEKDAYS = ['日', '一', '二', '三', '四', '五', '六'] as const;

/**
 * 当天日期段。`now` 只供测试注入。
 *
 * 三句话各有分工，删任何一句都会掉一个能力：
 * · 第一句给**事实**（今天几号、星期几）——没有它后面两句无从谈起；
 * · 第二句给**用法**（什么时候该用它、相对时间按它推算）——只给事实不给用法，
 *   模型仍可能对「下周」按训练数据里的年份去算；
 * · 第三句给**边界**（训练数据早于今天）——否则它会拿旧知识冒充「最近」，
 *   而「编一个像真的日期」比「说不确定」危害更大。
 */
export function buildDateBlock(now: Date = new Date()): string {
  const y = now.getFullYear();
  const m = now.getMonth() + 1; // getMonth() 是 0 基，忘了 +1 会整月错位
  const d = now.getDate();
  const w = WEEKDAYS[now.getDay()] ?? '日'; // getDay() 恒 0~6，`??` 只为满足索引越界检查

  return [
    `【当前日期】今天是 ${y}年${m}月${d}日（星期${w}）。`,
    '涉及「今天／今年／最近」这类时间判断时以该日期为准；用户说「明天／下周／还有几天」时按它推算。',
    '你的训练数据有截止日期、早于今天——近期事件若不确定就直说不确定，不要编日期。',
  ].join('\n');
}
