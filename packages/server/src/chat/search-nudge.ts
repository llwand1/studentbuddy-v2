/**
 * chat/search-nudge —— `search_web` 的触发增强（2026-09-17 新建，bug-ledger B-006 的修复层之一）。
 *
 * 【为什么需要这个文件】
 * 联网搜索的**工程链路从头到尾是通的**：`tools.ts` 注册了 `search_web`、两个适配器
 * （`llm/openai.ts` / `llm/anthropic.ts`）都带 `tools`、执行期有超时、SSE 帧登记完整，
 * 真机历史上也确实搜出过结果（2026-09-14 那轮三组结果都落进了 `messages` 表）。
 * 但实测里模型**经常直接回答"我这边没有联网搜索工具"**，连一次调用都不发。
 *
 * 根因不在链路，在**声明**与**触发**两处都缺：
 * ① `system-prompt.ts` 里 chart / html / update_tasks / ask_choice 全都有使用引导，
 *    **唯独 `search_web` 一个字都没提**——模型对「我自己有什么能力」的判断高度依赖
 *    系统提示词里的能力声明，"没被声明的工具"它不会算成自己的能力；
 * ② `tool_choice='auto'` 下模型完全自由，而助手的出厂倾向是**直接把答案讲完**，
 *    于是它宁可说"我没有这个功能"，也不去调一个自己没被告知的工具。
 *
 * 这与 `choice-nudge.ts` 记录的是**同一个坑**（AGENTS：「加工具不配触发层，模型就会永远不用它」），
 * 故照它的三层触发补齐：① 提示词场景清单 + 时序要求（`system-prompt.ts`）
 * ② 工具描述正面为主、带示例（`tools.ts`）③ **输入侧词表硬提醒（本文件）**。
 *
 * 【与 choice-nudge 的两处差异，别照搬】
 * ① **误伤代价不同**：`choice-nudge` 是「宁可漏不可误」——误弹选择框会直接打断讲解；
 *    联网这条**误搜的代价低**（多一次检索、百毫秒级，拿到结果用不上也无害），故词表可以放宽。
 *    **但仍要拦掉把「搜索」当学科术语的提问**（"二分搜索""搜索算法"）——那是知识问答，
 *    搜了只会让回答跑偏，故 `EXCLUDE_SIGNALS` 是它的守门人。
 * ② **优先级高于 choice**：学习者明确说「你联网搜索试试」时，这是**动作指令**不是岔路，
 *    实测里模型却弹了 `ask_choice` 让他先拍板（B-006 现场记录）。故在
 *    `context-segments.ts` 里两者同时命中时 **search 优先**，不给模型"先问再搜"的机会。
 *
 * 【设计红线】
 * · **只在首轮注入、用完即摘**：走既有的 `nudge` 段（`context-segments.ts` 组装、
 *   `flow.ts` 在 turn 0 之后 splice 摘除）——`flow.ts` 的编排与摘除逻辑**零改动**。
 * · 纯函数、零 IO —— 词表会随实测反复调，能单测才敢调。
 */

/**
 * 强信号：命中即认为「学习者在要求联网检索」。
 * 收得比 `choice-nudge` 宽（理由见文件头「误伤代价不同」），但每条都得对应**真实的检索诉求**。
 */
const SEARCH_SIGNALS = [
  // 点名联网渠道（最强信号，几乎无歧义）
  '联网', '上网', '网上搜', '网上查', '上网查', '在线搜', '在线查',
  // 明确下达检索动作——**含短指令**，故 MIN_LEN 不能取 4（"搜搜""搜下"只有两三个字）。
  // ★ 刻意**不收** '先搜'/'先查' 这类「短前缀」式信号（2026-09-17 实测踩到）：它们会被
  //   "优先搜索""优先查找"**假命中**，而那两句恰恰是要拦的学科术语 —— 前缀式信号一律不收，宁可漏。
  '搜搜', '搜一搜', '搜一下', '搜下', '搜索一下', '搜索试试', '搜索', '去搜', '帮我搜', '你搜',
  '查一下', '查查', '查下', '帮我查', '你查', '去查',
  // 点名检索引擎
  '百度', '谷歌', 'google', '必应', 'bing',
  // 时效性诉求：模型自身知识必然过时，本来就该检索
  '最新的', '最新消息', '最新进展', '最新情况', '最新动态', '今日新闻', '今天的新闻', '实时新闻', '实时行情',
];

/**
 * 排除信号：命中即判定为「学科术语 / 知识问答」，不该联网检索。
 * 这一栏是**误搜率的守门人**——本仓是学习场景，「搜索」极高频率作算法术语出现
 * （"二分搜索""搜索算法""广度优先搜索"），不拦就会把一道讲解题变成检索题。
 */
const EXCLUDE_SIGNALS = [
  '二分搜索', '二分查找', '线性搜索', '线性查找', '顺序搜索', '顺序查找',
  '搜索算法', '搜索树', '树搜索', '搜索二叉树', '搜索空间', '搜索路径', '搜索栏', '搜索框',
  '广度优先搜索', '深度优先搜索', '启发式搜索', '局部搜索', '回溯搜索', '爬山搜索',
  // "优先搜索/优先查找"（最佳优先搜索一族）——与信号表里已删的 '先搜'/'先查' 是同一处踩坑的兜底
  '优先搜索', '优先查找',
];

/**
 * 最短长度：低于此值不做判断。
 * 刻意取 **2** 而不是 `choice-nudge` 的 4——实测里"搜搜""搜下"本身就是完整诉求
 * （B-006 现场老板的原话之一就是"搜搜"），长度门槛一旦设成 4，这类短指令会整片漏掉。
 */
const MIN_LEN = 2;

/** 本轮硬指令正文（命中信号时追加进 messages，作用范围只有首轮） */
export const SEARCH_NUDGE =
  '（本轮学习者在要求联网检索，这是**动作指令**不是岔路。）' +
  '你**具备联网搜索能力**，可以调用 `search_web` 工具。' +
  '请**本轮第一个动作就调用 search_web**：不要先弹 ask_choice 让他拍板，也不要先写一段正文再问。' +
  '他给的线索再模糊（哪怕只有一个词）也直接用那个词做 query 搜——搜到了再判断有没有用，' +
  '而不是先反问他要搜什么。' +
  '只有确实没检索到内容时，才如实说"这次没搜到"，**绝不要回答自己没有联网能力**。';

/**
 * 判断这条用户消息是否在要求联网检索。
 * @returns 命中返回硬指令文本；否则 null（调用方据此决定是否注入）
 */
export function searchNudge(text: string): string | null {
  const s = (text ?? '').trim();
  if (s.length < MIN_LEN) return null;
  if (EXCLUDE_SIGNALS.some((w) => s.includes(w))) return null;
  if (!SEARCH_SIGNALS.some((w) => s.includes(w))) return null;
  return SEARCH_NUDGE;
}
