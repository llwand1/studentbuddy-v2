/**
 * chat/choice-nudge —— `ask_choice` 的触发增强（2026-09-14 夜）。
 *
 * 【为什么需要这个文件】
 * 方案选择框上线后实测：功能全通（工具已注册、两个适配器都带 tools、超时已豁免），
 * 但模型**几乎不主动调**。根因不在工程链路，而在触发条件太软：`tool_choice='auto'`
 * 下模型有完全自由，而「助手」的出厂倾向是**直接把答案讲完**——它不觉得"先问一句"是必要的。
 * 系统提示里那一句「遇到岔路时用 ask_choice」属于**原则性描述**，模型无法把它
 * 映射到具体句子上，于是退化成永远不调。
 *
 * 【手段：把「原则」降级成「匹配」】
 * 本文件做的是一件很土但很有效的事：用**词表匹配**识别用户这条消息是不是在做选择/规划，
 * 命中就在本轮上下文里追加一条**硬指令**（先问再答）。词表不改模型，只改它看到的输入。
 *
 * 【设计红线】
 * ① **宁可漏，不可误**：误弹一次（用户只想听讲解却被迫选）比漏弹十次更伤体验——
 *    故词表只收**几乎必然是选择/规划**的强信号，并设排除表拦掉求讲解/调试类。
 * ② **只在首轮注入、用完即摘**（见 flow.ts）：首轮过后这条指令必须移出 messages，
 *    否则后续轮（"那把第二个方案展开讲讲"）会被它误导再问一次。
 * ③ 纯函数、零 IO —— 词表会随实测反复调，能单测才敢调。
 */

/** 强信号：命中即认为「学习者在做选择/规划」，几乎不存在歧义 */
const CHOICE_SIGNALS = [
  // 明确授权 AI 替他选
  '帮我选', '帮我挑', '帮我定', '帮我决定', '帮我拿主意', '帮我看看怎么',
  // 直接问选哪个
  '选哪个', '选什么', '怎么选', '该选', '选哪种',
  // 「哪个更 X」类（注：'哪个优先' 不收——"线程和进程哪个优先级高"是知识问答，不是求助选择）
  '哪个更好', '哪个好', '哪个更合适', '哪个更适合', '哪个更值得',
  '优先学哪个', '优先做哪个', '优先看哪个',
  // 顺序/优先级类岔路（学习场景高频）
  '先学哪个', '先看哪个', '先做哪个', '先补哪个', '先刷哪', '先搞哪个',
  '从哪开始', '从哪儿开始', '从哪入手', '如何入手', '怎么开始', '如何开始', '怎么起步',
  // 计划/安排（天然多路线）
  '怎么安排', '如何安排', '怎么规划', '如何规划', '怎么复习', '如何复习',
  '学习计划', '复习计划', '备考计划', '制定计划', '列个计划',
  // 权衡类
  '要不要', '该不该', '应不应该', '值不值得', '有必要吗',
  // 明确索要方案（注：'有什么办法'/'有哪些方法' 不收——"二叉树遍历有哪些方法"是求列举讲解，
  // 弹个选择框属于打扰；真正想要方案的人会说"帮我选/给我几个方案"）
  '给几个方案', '给我几个方案', '给个路线', '给条路线',
  // "A 还是 B" 是最强的二选一结构（"按概念还是按题型""要详解还是速览"），必须收；
  // 它同时也是最容易误伤的词，故下面 EXCLUDE 里备了「还是不懂/还是不会」等追问态兜底。
  '还是',
];

/**
 * 排除信号：命中即判定为「求讲解 / 求排错」，不该弹选择框。
 * 这一栏是误弹率的守门人——宁可把边界词放进这里，也不要放进上表。
 */
const EXCLUDE_SIGNALS = [
  '区别', '是什么', '什么是', '什么意思', '原理', '为什么', '为何',
  '怎么实现', '如何实现', '怎么写', '怎么算', '怎么求', '怎么证明',
  '怎么用', '如何使用', '怎么调用', '怎么配置',
  '举个例子', '讲一下', '讲解', '解释', '详细说说', '展开讲',
  '代码', '报错', 'bug', '异常', '编译', '这道', '下列', '选择题', '优先级',
  '对不对', '是不是', '有没有错', '哪里错',
  // 「还是」的追问态兜底：'还是' 收进信号表后，这类"我还是没懂"必须拦掉
  '还是不懂', '还是不会', '还是不明白', '还是没懂', '还是没明白', '还是不行', '还是不对',
];

/** 最短长度：低于此值多半是闲聊/追问，不做判断（"在吗""继续"不该弹框） */
const MIN_LEN = 4;

/** 本轮硬指令正文（命中信号时追加进 messages，作用范围只有首轮） */
export const CHOICE_NUDGE =
  '（本轮输入里学习者正在做选择或规划，存在多条合理路线。）' +
  '你必须**先调用 ask_choice** 给出 2~4 个方案让他拍板，拿到答复后再在同一轮展开正文。' +
  '不要先写出一整段讲解或方案再问——先输出正文会让人以为已经讲完了，选择框就没人点了。';

/**
 * 判断这条用户消息是否需要「先问再答」的硬提醒。
 * @returns 命中返回硬指令文本；否则 null（调用方据此决定是否注入）
 */
export function choiceNudge(text: string): string | null {
  const s = (text ?? '').trim();
  if (s.length < MIN_LEN) return null;
  if (EXCLUDE_SIGNALS.some((w) => s.includes(w))) return null;
  if (!CHOICE_SIGNALS.some((w) => s.includes(w))) return null;
  return CHOICE_NUDGE;
}
